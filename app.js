function updateImageState(state) {
  if (!activeImage) return;
  imageState = state;
  const i = lang === "es" ? 1 : 0;
  imageStage.setAttribute("aria-busy", String(state === "loading"));
  zoomButton.disabled = state !== "ready";
  retryButton.hidden = state !== "error";
  retryButton.textContent = imageMessages.retry[i];
  imageCaption.textContent =
    state === "ready" ? imageDescription() : imageMessages[state][i];
}
function renderImage(reload = false) {
  if (!activeImage) return;
  const image = imageContent[activeImage],
    i = lang === "es" ? 1 : 0;
  document.querySelector("#image-dialog-title").textContent = image.title[i];
  expandedImage.alt = image.alt[i];
  if (reload || expandedImage.getAttribute("src") !== image.src) {
    updateImageState("loading");
    expandedImage.src = image.src;
    if (expandedImage.complete)
      updateImageState(expandedImage.naturalWidth ? "ready" : "error");
  } else updateImageState(imageState === "idle" ? "loading" : imageState);
  updateZoomLabel();
}
