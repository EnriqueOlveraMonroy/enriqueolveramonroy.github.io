function applyFilter(filter, updateUrl = false) {
  filter = allowedFilters.has(filter) ? filter : "all";
  activeFilter = filter;
  let count = 0;
  if (updateUrl) {
    const url = new URL(location.href);
    if (filter === "all") url.searchParams.delete("category");
    else url.searchParams.set("category", filter);
    if (url.href !== location.href) history.pushState(null, "", url);
  }

  document.querySelectorAll("[data-category]").forEach((project) => {
    project.hidden = filter !== "all" && project.dataset.category !== filter;
    if (!project.hidden) count++;
  });
  document
    .querySelectorAll("[data-filter]")
    .forEach((button) =>
      button.setAttribute(
        "aria-pressed",
        String(button.dataset.filter === filter),
      ),
    );
  document.querySelector(".dashboard-grid").hidden = !["all", "bi"].includes(
    filter,
  );
  document.querySelector("#project-directory").hidden = ![
    "all",
    "analysis",
    "ml",
  ].includes(filter);
  document.querySelector(".web-collection").hidden = !["all", "web"].includes(
    filter,
  );
  document.querySelector("#project-count").textContent =
    lang === "es"
      ? `${count} ${count === 1 ? "proyecto" : "proyectos"}`
      : `${count} ${count === 1 ? "project" : "projects"}`;
}
